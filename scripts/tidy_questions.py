#!/usr/bin/env python3
"""Tidy exam paper PDFs into clean per-question JSON using a vision LLM.

Each paper PDF is rendered page by page and sent to a vision model together
with the answer-key PDF images. The model extracts every COMPLETE question
visible on the page. Because some questions span two pages, the previous
page's last question is carried forward: the model may return an
``updated_previous`` that merges content across the boundary, plus any
``questions`` that are newly complete on the current page.

The LLM's role is TIDYING, not grading: it faithfully transcribes the paper's
and the official answer key's content — including any mistakes in the key.
Accuracy is checked separately by scripts/validate_tidy_questions.py.

Output schema per question (all text fields are Markdown):
    {
      "background":   string,  # Markdown, equations as LaTeX
      "question":     string,  # Markdown
      "options":      [{"code": "A", "label": "..."}],
      "answer":       string,
      "explanations": string,  # Markdown
      "section":      "reading_writing" | "math",
      "module":       1 | 2,
      "number":       int,
      "page":         int      # source page_idx
    }

Usage:
    python scripts/tidy_questions.py \\
        --model gpt-5.6-terra \\
        --pair papers/pdfs/2024/demo-paper.pdf \\
               papers/pdfs/2024/demo-key.pdf
"""

